using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace MethodsAssignment
{
    public class Integer
    {
        ///<summary>
        ///Returns the input divided by 3
        ///</summary>  
        public static int  Divide(int value) 
        {
            return value / 3;
        }

        ///<summary>
        ///Returns input multiplied by 36.5
        ///</summary>
        public static double Times(double value)
        {
            return value * 36.5;
        }

        ///<summary>
        ///Returns input subtracted by 20
        ///</summary>
        public static int Minus(int value)
        {
            return value - 20;
        }

    }
}
